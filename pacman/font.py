_cache = {}


def glyph(ch, color):
    key = (ch, color)
    surf = _cache.get(key)
    if surf is None:
        surf = pygame.Surface((TILE, TILE), pygame.SRCALPHA)
        for y, row in enumerate(GLYPHS.get(ch, ())):
            for x, bit in enumerate(row):
                if bit == "#":
                    surf.set_at((x, y), color)
        _cache[key] = surf
    return surf


def draw_text_px(surf, text, x, y, color):
    for i, ch in enumerate(text.upper()):
        surf.blit(glyph(ch, color), (x + i * TILE, y))


def draw_text(surf, text, col, row, color):
    """Draw text on the 28x36 tile grid."""
    draw_text_px(surf, text, col * TILE, row * TILE, color)


def draw_text_right(surf, text, right_col, row, color):
    draw_text(surf, text, right_col - len(text) + 1, row, color)
